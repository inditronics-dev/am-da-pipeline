# =========================================================
# STAGE 1 - LOGO VALIDATION CHECKS
# =========================================================

# =========================================================
# IMPORT LIBRARIES
# =========================================================
import pandas as pd
import os
import sys
from datetime import datetime, timedelta

from openpyxl import load_workbook
from openpyxl.styles import PatternFill, Font

from file_path import *
# =========================================================
# GET PROCESS DATE (D-1 from main pipeline)
# ========================================================

run_date = (
    os.environ.get("RUN_DATE")
    or os.environ.get("WORKFLOW_DATE")
)

# If running outside the pipeline, default to D-1
if not run_date:
    run_date = (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d")

# Convert YYYY-MM-DD to DD-MM-YYYY
process_date = datetime.strptime(
    run_date,
    "%Y-%m-%d"
).strftime("%d-%m-%Y")
# =========================================================
# PROJECT ROOT
# =========================================================
BASE_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..")
)

# =========================================================
# INPUT FILE (Generated by Pipeline)
# =========================================================
LOGO_FILE = os.path.join(
    BASE_DIR,
    "sessions",
    "logo",
    "household_viewership_memberwise_output",
    f"{run_date}_logo_sessions.csv"
)

print("\n===================================")
print("STAGE 1 - LOGO VALIDATION")
print("===================================")

print(f"\nLogo File : {LOGO_FILE}")

# =========================================================
# CHECK FILE EXISTS
# =========================================================
if not os.path.exists(LOGO_FILE):

    raise Exception(
        f"Logo file not found : {LOGO_FILE}"
    )

# =========================================================
# READ FILE
# =========================================================
df = pd.read_csv(LOGO_FILE)

# =========================================================
# CLEAN COLUMN NAMES
# =========================================================
df.columns = df.columns.str.strip().str.lower()

# =========================================================
# CREATE OUTPUT FILE IF NOT EXISTS
# =========================================================
import shutil

# =========================================================
# TEMPLATE AND OUTPUT FILE
# =========================================================
VALIDATION_FILE = os.path.join(
    os.path.dirname(__file__),
    "Data Validation Check.xlsx"
)

OUTPUT_FILE = os.path.join(
    os.path.dirname(__file__),
    "Data Validation Check Completed.xlsx"
)

# Always create a fresh copy of the template
shutil.copy2(
    VALIDATION_FILE,
    OUTPUT_FILE
)

# Open the copied workbook
wb = load_workbook(OUTPUT_FILE)
ws = wb.active

# =========================================================
# UPDATE PROCESS DATE
# =========================================================
ws["D2"] = process_date

# =========================================================
# COLORS
# =========================================================
GREEN_FILL = PatternFill(
    start_color="90EE90",
    end_color="90EE90",
    fill_type="solid"
)

RED_FILL = PatternFill(
    start_color="FF9999",
    end_color="FF9999",
    fill_type="solid"
)

YELLOW_FILL = PatternFill(
    start_color="FFF59D",
    end_color="FFF59D",
    fill_type="solid"
)

BOLD_FONT = Font(bold=True)


# =========================================================
# UPDATE VALIDATION ROW
# =========================================================
def update_validation_row(row_no, status, remarks=""):

    status_cell = ws.cell(row=row_no, column=4)   # Column E
    remarks_cell = ws.cell(row=row_no, column=5)  # Column F

    status_cell.value = status
    status_cell.font = BOLD_FONT

    # Clear old remarks
    remarks_cell.value = ""
    remarks_cell.fill = PatternFill(fill_type=None)

    if status == "PASS":
        status_cell.fill = GREEN_FILL

    elif status == "FAIL":
        status_cell.fill = RED_FILL
        remarks_cell.value = remarks

    else:
        status_cell.fill = YELLOW_FILL
        remarks_cell.value = remarks

    print(f"Updated Row {row_no} : {status}")
# =========================================================
# CREATE START & END DATETIME
# =========================================================

df["start_datetime"] = pd.to_datetime(
    df["date"].astype(str).str.strip()
    + " "
    + df["start_time"].astype(str).str.strip(),
    errors="coerce"
)

df["end_datetime"] = pd.to_datetime(
    df["date"].astype(str).str.strip()
    + " "
    + df["end_time"].astype(str).str.strip(),
    errors="coerce"
)

# =========================================================
# NULL CHECK
# =========================================================
null_datetime = (
    df["start_datetime"]
    .isna()
    .sum()
)

# =========================================================
# VALIDATION 1
# FULL HOURS CHECK
# =========================================================
input_date = datetime.strptime(
    process_date,
    "%d-%m-%Y"
)

next_day = input_date + timedelta(days=1)

date1 = input_date.strftime("%Y-%m-%d")

date2 = next_day.strftime("%Y-%m-%d")

day1_df = df[
    df["start_datetime"]
    .dt.strftime("%Y-%m-%d")
    == date1
]

day2_df = df[
    df["end_datetime"]
    .dt.strftime("%Y-%m-%d")
    == date2
]

# First session should start at 02:00
day1_min = day1_df["start_datetime"].min()

# Last session on Day 1 should end at 23:59
day1_max = day1_df["end_datetime"].max()

# Last session on Day 2 should end at 01:59
day2_max = day2_df["end_datetime"].max()

pass_flag = True

remarks = []

# ---------------------------------------------------------
# DAY 1 START
# ---------------------------------------------------------
if day1_min.strftime("%H:%M") != "02:00":

    pass_flag = False

    remarks.append(
        f"Day1 Start={day1_min.strftime('%H:%M:%S')}"
    )

# ---------------------------------------------------------
# DAY 1 END
# ---------------------------------------------------------
if day1_max.strftime("%H:%M") != "23:59":

    pass_flag = False

    remarks.append(
        f"Day1 End={day1_max.strftime('%H:%M:%S')}"
    )

# ---------------------------------------------------------
# DAY 2 END
# ---------------------------------------------------------
if day2_max.strftime("%H:%M") != "01:59":

    pass_flag = False

    remarks.append(
        f"Day2 End={day2_max.strftime('%H:%M:%S')}"
    )

# ---------------------------------------------------------
# FINAL
# ---------------------------------------------------------
if pass_flag:

    update_validation_row(3, "PASS")

else:
    update_validation_row(
    3,
    "FAIL",
    " | ".join(remarks)
    )

    

# =========================================================
# VALIDATION 2
# NEGATIVE DURATION
# =========================================================
negative_df = df[
    df["duration_seconds"] < 0
]

if len(negative_df) == 0:

    update_validation_row(4, "PASS")

else:

    update_validation_row(
    4,
    "FAIL",
    f"{len(negative_df)} negative duration rows found"
    )

# =========================================================
# SAVE OUTPUT
# =========================================================
wb.save(OUTPUT_FILE)

print("\n===================================")
print("LOGO VALIDATION COMPLETED")
print("===================================")